'use strict';

// Компактный слепок "что за клиент" для метрик relay-сервера (см.
// relay/src/metrics.js). Уезжает полем client в теле POST /events.
//
// Зачем это вообще собирается: расширение само в сеть не ходит и ходить не
// должно, поэтому единственный компонент, который достоверно знает ОС и
// версию хоста — сам хост. Без этого на вопросы "под какую ОС собирать
// бинарники", "у скольких юзеров хост отстал от расширения" и "живой ли
// вообще dev-путь установки" ответить нечем.
//
// Важное ограничение охвата: сюда попадают ТОЛЬКО юзеры relay-провайдера.
// Кто настроил свой ntfy/Pushover/свой бот или не включал телефонный канал
// вообще — до сервера не доходит по определению, и в статистике его нет.
// Это осознанный размен: отдельный телеметрический пинг с хоста дал бы
// полный охват, но превратил бы локальный инструмент в продукт с фоновой
// отправкой данных. Читать любые доли по ОС нужно с этой поправкой.

const os = require('os');
const platform = require('./platform');
const { hostVersion } = require('./constants');

function clientInfo() {
  const { os: osName, osVersion } = platform.osInfo();
  return {
    os: osName,
    osVersion,
    // x64 vs arm64 — прямой ответ на "нужна ли отдельная сборка под Apple
    // Silicon", по одному лишь названию ОС этого не видно.
    arch: os.arch(),
    hostVersion: hostVersion(),
    // Под pkg-бинарником process.pkg определён, при запуске через node — нет.
    // Показывает, каким из двух путей установки (exe / npm + node) реально
    // пользуются, а не каким мы думаем, что пользуются.
    packaged: typeof process.pkg !== 'undefined',
  };
}

module.exports = { clientInfo };
